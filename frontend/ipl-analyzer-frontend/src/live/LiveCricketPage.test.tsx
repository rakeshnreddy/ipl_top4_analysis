import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import LiveCricketPage from './LiveCricketPage';
import { loadFreeDetail, loadFreeMatches } from '../data/freeCricket';
import { detailFixture, listFixture } from './testFixtures';
vi.mock('../data/freeCricket', () => ({ loadFreeMatches: vi.fn(async () => listFixture()), loadFreeDetail: vi.fn(async () => detailFixture()) }));
beforeEach(() => { vi.mocked(loadFreeMatches).mockImplementation(async () => listFixture()); vi.mocked(loadFreeDetail).mockImplementation(async () => detailFixture()); });
afterEach(() => { cleanup(); window.history.replaceState({}, '', '/cricket/'); vi.unstubAllGlobals(); vi.unstubAllEnvs(); });
describe('Live Cricket match center', () => {
  it('keeps missing models and bookmaker prices unavailable without invented numbers', async () => {
    window.history.replaceState({}, '', '/cricket/?match=synthetic-one');
    render(<LiveCricketPage />);
    await waitFor(() => expect(screen.getByRole('heading', { name: 'Synthetic Alpha v Synthetic Beta' })).toBeInTheDocument());
    fireEvent.click(screen.getByRole('tab', { name: 'Model win chance' }));
    await screen.findByRole('heading', { name: 'Match win model not available' });
    expect(screen.getByRole('tabpanel')).toHaveTextContent('Unavailable');
    expect(screen.getByRole('tabpanel')).not.toHaveTextContent('50%');
    fireEvent.click(screen.getByRole('tab', { name: 'Bookmaker odds' }));
    await screen.findByRole('heading', { name: 'Bookmaker prices not supplied' });
    expect(screen.getByRole('tabpanel')).toHaveTextContent('Unavailable');
    expect(screen.getByRole('tabpanel')).not.toHaveTextContent('0.00');
    expect(screen.getByRole('link', { name: 'Powered by SportScore' })).toHaveAttribute('href', 'https://sportscore.com/');
  });
  it('never labels a paused bookmaker snapshot current and rechecks on resume', async () => {
    const detail = detailFixture();
    const stamp = new Date().toISOString();
    detail.generatedAt = stamp; detail.match.observedAt = stamp;
    detail.markets = { status: 'available', source: 'Synthetic bookmaker source', observedAt: stamp, fetchedAt: stamp, reason: null, data: [{ key: 'test-book', title: 'Synthetic Bookmaker', updatedAt: stamp, markets: [{ key: 'winner', name: 'Match winner', state: 'open', updatedAt: stamp, settlement: 'Synthetic settled result', outcomes: [{ name: 'Synthetic Alpha', price: 1.75 }, { name: 'Synthetic Beta', price: 2.25 }] }] }] };
    vi.mocked(loadFreeDetail).mockResolvedValue(detail);
    window.history.replaceState({}, '', '/cricket/?match=synthetic-one');
    render(<LiveCricketPage />);
    await screen.findByRole('heading', { name: 'Synthetic Alpha v Synthetic Beta' });
    fireEvent.click(screen.getByRole('tab', { name: 'Bookmaker odds' }));
    await screen.findByText('1.75');
    expect(screen.getAllByText('Current quote')).toHaveLength(2);
    fireEvent.click(screen.getByRole('button', { name: 'Pause updates' }));
    expect(screen.queryByText('Current quote')).not.toBeInTheDocument();
    expect(screen.getByRole('tabpanel')).toHaveTextContent('Updates paused');
    expect(screen.getByRole('tabpanel')).toHaveTextContent('Last quoted price · not current');
    const calls = vi.mocked(loadFreeDetail).mock.calls.length;
    fireEvent.click(screen.getByRole('button', { name: 'Resume updates' }));
    await waitFor(() => expect(vi.mocked(loadFreeDetail).mock.calls.length).toBeGreaterThan(calls));
  });
  it('keeps commentary in place until the reader accepts a source correction', async () => {
    const detail = detailFixture();
    const stamp = new Date().toISOString();
    detail.commentary = { status: 'available', source: 'Synthetic source', observedAt: stamp, fetchedAt: stamp, reason: null, data: [{ id: 'ball-1', sequence: 1, innings: 'First innings', over: '0.1', batter: 'Test batter', bowler: 'Test bowler', runs: 4, extras: 0, wickets: 0, text: 'Original boundary call', observedAt: stamp, revision: 'one' }] };
    vi.mocked(loadFreeDetail).mockResolvedValue(detail);
    window.history.replaceState({}, '', '/cricket/?match=synthetic-one');
    render(<LiveCricketPage />);
    await screen.findByRole('heading', { name: 'Synthetic Alpha v Synthetic Beta' });
    fireEvent.click(screen.getByRole('tab', { name: 'Commentary' }));
    await screen.findByText('Original boundary call');
    const correction = structuredClone(detail);
    correction.commentary.data![0].text = 'Corrected to three runs'; correction.commentary.data![0].runs = 3; correction.commentary.data![0].revision = 'two';
    vi.mocked(loadFreeDetail).mockResolvedValue(correction);
    fireEvent.click(screen.getByRole('button', { name: 'Refresh' }));
    await screen.findByRole('button', { name: 'Show 1 new or corrected delivery' });
    expect(screen.getByText('Original boundary call')).toBeInTheDocument();
    expect(screen.queryByText('Corrected to three runs')).not.toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: 'Show 1 new or corrected delivery' }));
    expect(screen.getAllByText('Corrected to three runs')).toHaveLength(1);
    expect(screen.queryByText('Original boundary call')).not.toBeInTheDocument();
  });
  it.each(['Bookmaker odds', 'Model win chance'])('withholds current %s when the detail connection fails', async (tab) => {
    const detail = detailFixture(); const stamp = new Date().toISOString();
    detail.generatedAt = stamp; detail.match.observedAt = stamp;
    detail.markets = { status: 'available', source: 'Synthetic quote source', observedAt: stamp, fetchedAt: stamp, reason: null, data: [{ key: 'test-book', title: 'Synthetic Bookmaker', updatedAt: stamp, markets: [{ key: 'winner', name: 'Match winner', state: 'open', updatedAt: stamp, settlement: 'Synthetic test outcome', outcomes: [{ name: 'Synthetic Alpha', price: 1.75 }, { name: 'Synthetic Beta', price: 2.25 }] }] }] };
    detail.model = { status: 'available', source: 'Synthetic model', observedAt: stamp, fetchedAt: stamp, reason: null, data: { modelId: 'test', modelVersion: 'test', scoreRevision: detail.match.revision, predictedAt: stamp, conditioning: 'Synthetic completed match', probabilities: [{ outcome: 'Synthetic Alpha', probability: 0.7 }, { outcome: 'Synthetic Beta', probability: 0.3 }], history: [] } };
    vi.mocked(loadFreeDetail).mockResolvedValue(detail);
    window.history.replaceState({}, '', '/cricket/?match=synthetic-one'); render(<LiveCricketPage />);
    await screen.findByRole('heading', { name: 'Synthetic Alpha v Synthetic Beta' });
    fireEvent.click(screen.getByRole('tab', { name: tab }));
    await screen.findByText(tab === 'Bookmaker odds' ? '1.75' : '70%');
    vi.mocked(loadFreeDetail).mockRejectedValue(new Error('Synthetic source outage'));
    fireEvent.click(screen.getByRole('button', { name: 'Refresh' }));
    await screen.findByText('Connection lost. Last verified data is retained.');
    expect(screen.getByRole('tabpanel')).toHaveTextContent('Connection interrupted');
    expect(screen.queryByText('Current quote')).not.toBeInTheDocument();
    if (tab === 'Bookmaker odds') expect(screen.getByRole('tabpanel')).toHaveTextContent('1.75');
    else expect(screen.getByRole('tabpanel')).not.toHaveTextContent('70%');
  });
  it('withholds a probability estimate from the wrong score revision', async () => {
    const detail = detailFixture(); const stamp = new Date().toISOString();
    detail.model = { status: 'available', source: 'Synthetic model', observedAt: stamp, fetchedAt: stamp, reason: null, data: { modelId: 'test', modelVersion: 'test', scoreRevision: 'earlier-revision', predictedAt: stamp, conditioning: 'Synthetic completed match', probabilities: [{ outcome: 'Synthetic Alpha', probability: 0.7 }, { outcome: 'Synthetic Beta', probability: 0.3 }], history: [] } };
    vi.mocked(loadFreeDetail).mockResolvedValue(detail);
    window.history.replaceState({}, '', '/cricket/?match=synthetic-one'); render(<LiveCricketPage />);
    await screen.findByRole('heading', { name: 'Synthetic Alpha v Synthetic Beta' });
    fireEvent.click(screen.getByRole('tab', { name: 'Model win chance' }));
    await screen.findByText('Current model estimate unavailable');
    expect(screen.getByRole('tabpanel')).not.toHaveTextContent('70%');
    expect(screen.getByRole('tabpanel')).toHaveTextContent('earlier score revision');
  });
  it('does not let a new collection timestamp refresh an old prediction', async () => {
    const detail = detailFixture(); const stamp = new Date().toISOString();
    detail.generatedAt = stamp; detail.match.observedAt = stamp;
    detail.model = { status: 'available', source: 'Synthetic model', observedAt: stamp, fetchedAt: stamp, reason: null, data: { modelId: 'test', modelVersion: 'test', scoreRevision: detail.match.revision, predictedAt: new Date(Date.now() - 600_000).toISOString(), conditioning: 'Synthetic completed match', probabilities: [{ outcome: 'Synthetic Alpha', probability: 0.7 }, { outcome: 'Synthetic Beta', probability: 0.3 }], history: [] } };
    vi.mocked(loadFreeDetail).mockResolvedValue(detail);
    window.history.replaceState({}, '', '/cricket/?match=synthetic-one'); render(<LiveCricketPage />);
    await screen.findByRole('heading', { name: 'Synthetic Alpha v Synthetic Beta' });
    fireEvent.click(screen.getByRole('tab', { name: 'Model win chance' }));
    await screen.findByText('Current model estimate unavailable');
    expect(screen.getByRole('tabpanel')).not.toHaveTextContent('70%');
    expect(screen.getByRole('tabpanel')).toHaveTextContent('overdue');
  });
  it.each(['source event', 'feed publication'])('withholds a fresh prediction when its parent %s is overdue', async (clock) => {
    const detail = detailFixture(); const stamp = new Date().toISOString();
    const earlier = new Date(Date.now() - 600_000).toISOString();
    detail.generatedAt = clock === 'source event' ? stamp : earlier;
    detail.match.observedAt = clock === 'source event' ? earlier : null;
    detail.match.fetchedAt = stamp;
    detail.model = { status: 'available', source: 'Synthetic model', observedAt: null, fetchedAt: stamp, reason: null, data: { modelId: 'test', modelVersion: 'test', scoreRevision: detail.match.revision, predictedAt: stamp, conditioning: 'Synthetic completed match', probabilities: [{ outcome: 'Synthetic Alpha', probability: 0.7 }, { outcome: 'Synthetic Beta', probability: 0.3 }], history: [] } };
    vi.mocked(loadFreeDetail).mockResolvedValue(detail);
    window.history.replaceState({}, '', '/cricket/?match=synthetic-one'); render(<LiveCricketPage />);
    await screen.findByRole('heading', { name: 'Synthetic Alpha v Synthetic Beta' });
    fireEvent.click(screen.getByRole('tab', { name: 'Model win chance' }));
    await screen.findByText('Current model estimate unavailable');
    expect(screen.getByRole('tabpanel')).not.toHaveTextContent('70%');
    expect(screen.getByRole('tabpanel')).toHaveTextContent('overdue');
  });
  it('uses a fresh feed publication when a parent event time is not supplied', async () => {
    const detail = detailFixture(); const stamp = new Date().toISOString();
    detail.generatedAt = stamp; detail.match.observedAt = null;
    detail.model = { status: 'available', source: 'Synthetic model', observedAt: null, fetchedAt: stamp, reason: null, data: { modelId: 'test', modelVersion: 'test', scoreRevision: detail.match.revision, predictedAt: stamp, conditioning: 'Synthetic completed match', probabilities: [{ outcome: 'Synthetic Alpha', probability: 0.7 }, { outcome: 'Synthetic Beta', probability: 0.3 }], history: [] } };
    vi.mocked(loadFreeDetail).mockResolvedValue(detail);
    window.history.replaceState({}, '', '/cricket/?match=synthetic-one'); render(<LiveCricketPage />);
    await screen.findByRole('heading', { name: 'Synthetic Alpha v Synthetic Beta' });
    fireEvent.click(screen.getByRole('tab', { name: 'Model win chance' }));
    await screen.findByText('70%');
    expect(screen.getByRole('tabpanel')).toHaveTextContent('Chance of winning this match');
  });
  it('describes a source failure as unknown coverage and allows a retry', async () => {
    vi.mocked(loadFreeMatches).mockRejectedValueOnce(new Error('Test outage'));
    render(<LiveCricketPage />);
    await screen.findByText('Match coverage cannot be checked.');
    expect(screen.queryByText('No live matches in the current coverage.')).not.toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: 'Try again' }));
    await screen.findByRole('link', { name: /Synthetic Alpha.*Synthetic Beta/ });
  });
  it('provides status filters, an honest coverage empty state and back navigation', async () => {
    render(<LiveCricketPage />);
    await screen.findByRole('link', { name: /Synthetic Alpha.*Synthetic Beta/ });
    fireEvent.click(screen.getByRole('button', { name: 'Upcoming' }));
    expect(screen.getByText('No upcoming matches in the current coverage.')).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: 'Live' }));
    fireEvent.click(screen.getByRole('link', { name: /Synthetic Alpha.*Synthetic Beta/ }));
    await waitFor(() => expect(screen.getByRole('heading', { name: 'Synthetic Alpha v Synthetic Beta' })).toHaveFocus());
    expect(window.location.search).toBe('?match=synthetic-one');
    fireEvent.click(screen.getByRole('link', { name: 'All matches' }));
    expect(window.location.search).toBe('');
    await waitFor(() => expect(screen.getByRole('heading', { name: 'Matches', exact: true })).toHaveFocus());
  });
});
